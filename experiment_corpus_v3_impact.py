#!/usr/bin/env python3
"""Does recovering the eCFR item bodies actually raise recall?

HANDOFF section 6 proposed heading-stub recovery as the highest-value remaining
task, on the reasoning that 42 of 71 validated queries have a gold document that
is nothing but a heading, so the parameters a query must match are absent from
the corpus and cap absolute recall. Corpus v3 recovers those bodies: eCFR text
goes 105,567 -> 814,646 characters and, on a content-based definition, entries
with no technical body drop 475 -> 48 and gold-all-stub queries drop 47 -> 1.

That is a large change to the corpus. This measures whether it changes retrieval,
and if not, why not -- because "the fix did not help" is only useful with the
mechanism attached.

    python experiment_corpus_v3_impact.py            # BM25 only, no encoder
    python experiment_corpus_v3_impact.py --dense    # + MiniLM

Outputs: output/corpus_v3_impact.{json,md}
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

import retrieval_core as rc

ROOT = Path(__file__).resolve().parent
V2 = ROOT / "data" / "corpus" / "combined_v2.json"
V3 = ROOT / "data" / "corpus" / "combined_v3.json"
QUERIES = ROOT / "data" / "validated_queries_expanded.json"
OUT_DIR = ROOT / "output"
JSON_PATH = OUT_DIR / "corpus_v3_impact.json"
MD_PATH = OUT_DIR / "corpus_v3_impact.md"

INDEX_MODES = ["minimal_text", "full_text"]
DENSE_MODEL = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
PRIMARY_ALPHA = 0.5
SEED = 20260626


def evaluate(corpus, queries, imode, model=None):
    docs = [rc.index_text(e, imode) for e in corpus]
    codes = [e["code"] for e in corpus]
    index = rc.BM25(docs)
    out = {"BM25": []}
    demb = qemb = None
    if model is not None:
        out.update({"dense": [], f"hybrid_{PRIMARY_ALPHA}": []})
        demb = model.encode(docs, batch_size=32, normalize_embeddings=True,
                            show_progress_bar=False).astype(np.float32)
        qemb = model.encode([q["query"] for q in queries], batch_size=32,
                            normalize_embeddings=True,
                            show_progress_bar=False).astype(np.float32)
    for qi, q in enumerate(queries):
        raw = index.scores(q["query"])
        labels = set(q["validated_labels"])
        out["BM25"].append(int(any(codes[i] in labels for i in rc.retrieve(raw, 10))))
        if model is None:
            continue
        bm, dn = rc.minmax(raw), rc.minmax(demb @ qemb[qi])
        for name, a in (("dense", 0.0), (f"hybrid_{PRIMARY_ALPHA}", PRIMARY_ALPHA)):
            top10 = list(rc.rank_indices(rc.blend(bm, dn, a))[:10])
            out[name].append(int(any(codes[i] in labels for i in top10)))
    return out


def truncation_profile(corpus, imode, model) -> dict:
    """How much of the indexed text the encoder actually sees."""
    tok = model.tokenizer
    ec = [e for e in corpus if e["source"] == "ecfr_part774"]
    lens = [len(tok.encode(rc.index_text(e, imode), add_special_tokens=True)) for e in ec]
    cap = model.max_seq_length
    return {"max_seq_length": cap, "n": len(lens),
            "median_tokens": int(np.median(lens)),
            "truncated": int(sum(1 for L in lens if L > cap)),
            "truncated_share": round(sum(1 for L in lens if L > cap) / len(lens), 4)}


def query_anchor(corpus3, queries) -> dict:
    """Are the queries lexically closer to the heading or to the recovered body?

    The validated slices were reverse-generated by reading the corpus as it then
    was, i.e. the heading. If the queries describe headings, adding item bodies
    cannot help them match and can only dilute.
    """
    by = {e["code"]: e for e in corpus3}
    jh, ji, n = [], [], 0
    for q in queries:
        e = by.get(q["validated_labels"][0])
        if not e or not (e.get("items_controlled") or "").strip():
            continue
        qt = set(rc.tokenize(q["query"]))
        if not qt:
            continue
        h = set(rc.tokenize(e.get("heading", "")))
        it = set(rc.tokenize(e.get("items_controlled", "")))
        jh.append(len(qt & h) / max(len(qt | h), 1))
        ji.append(len(qt & it) / max(len(qt | it), 1))
        n += 1
    return {"n": n,
            "jaccard_query_vs_heading": round(float(np.mean(jh)), 4) if jh else None,
            "jaccard_query_vs_items": round(float(np.mean(ji)), 4) if ji else None}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dense", action="store_true")
    args = ap.parse_args()

    c2 = json.loads(V2.read_text(encoding="utf-8"))
    c3 = json.loads(V3.read_text(encoding="utf-8"))
    queries = json.loads(QUERIES.read_text(encoding="utf-8"))["queries"]
    langs = [q["lang"] for q in queries]

    model = None
    if args.dense:
        from sentence_transformers import SentenceTransformer
        model = SentenceTransformer(DENSE_MODEL)

    results, contrasts, trunc = {}, {}, {}
    for imode in INDEX_MODES:
        h2 = evaluate(c2, queries, imode, model)
        h3 = evaluate(c3, queries, imode, model)
        block = {}
        for name in h2:
            a, b = h3[name], h2[name]
            diffs = [x - y for x, y in zip(a, b)]
            sub = {}
            for lang in (None, "en", "ko"):
                tag = lang or "overall"
                va = [x for x, lg in zip(a, langs) if lang is None or lg == lang]
                vb = [x for x, lg in zip(b, langs) if lang is None or lg == lang]
                sub[tag] = {"v2": rc.rate_with_ci(vb), "v3": rc.rate_with_ci(va)}
            block[name] = {
                "by_subgroup": sub,
                "paired_bootstrap": rc.paired_bootstrap_ci(diffs, seed=SEED),
                "mcnemar": rc.exact_mcnemar(a, b),
            }
        results[imode] = block
        contrasts[imode] = {k: v["paired_bootstrap"]["mean"] for k, v in block.items()}
        if model is not None:
            trunc[imode] = {"v2": truncation_profile(c2, imode, model),
                            "v3": truncation_profile(c3, imode, model)}

    out = {
        "question": "eCFR 표제 스텁 본문 복구가 검색 성능을 올리는가",
        "env": rc.env_meta({"seed": SEED, "dense": args.dense}),
        "results": results,
        "truncation": trunc,
        "query_anchor": query_anchor(c3, queries) if args.dense or True else {},
        "verdict": verdict(results, trunc),
    }
    OUT_DIR.mkdir(exist_ok=True)
    JSON_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    MD_PATH.write_text(render(out), encoding="utf-8")
    print(json.dumps({"contrasts": contrasts, "verdict": out["verdict"]},
                     ensure_ascii=False, indent=2))


def verdict(results: dict, trunc: dict) -> dict:
    prim = f"hybrid_{PRIMARY_ALPHA}"
    sig = []
    for imode, block in results.items():
        if prim not in block:
            continue
        ci = block[prim]["paired_bootstrap"]["ci"]
        if ci[0] > 0:
            sig.append(imode)
    if sig:
        return {"label": "helps",
                "text": f"{', '.join(sig)} 색인에서 hybrid R@10 이 유의하게 올랐다. v3 채택을 권고한다."}
    return {
        "label": "no_significant_gain",
        "text": ("어느 색인 모드에서도 hybrid R@10 이 유의하게 오르지 않았다. "
                 "표제 스텁은 절대 성능의 상한 요인이 아니었다 — 가설이 측정으로 반증됐다. "
                 "v3를 활성 코퍼스로 채택할 근거가 없다."),
    }


def render(o: dict) -> str:
    L = [f"# 코퍼스 v3(표제 스텁 보강)의 검색 성능 영향", "",
         f"**질문.** {o['question']}", "",
         "HANDOFF §6 은 이 작업을 '절대 성능의 최대 상한 요인'으로 지목했다. "
         "코퍼스는 크게 달라졌다(eCFR 본문 105,567 → 814,646자, 내용 기준 스텁 475 → 48, "
         "정답이 전부 스텁인 질의 47 → 1). 성능이 따라 오르는지 측정한다.", "",
         "## R@10 (검증셋 n=71)", "",
         "| 색인 | 검색기 | v2 | v3 | 차이 | 95% CI | 승/패/무 | exact p |",
         "|---|---|---:|---:|---:|---|---:|---:|"]
    for imode, block in o["results"].items():
        for name, r in block.items():
            s = r["by_subgroup"]["overall"]
            b, mc = r["paired_bootstrap"], r["mcnemar"]
            L.append(f"| {imode} | {name} | {s['v2']['rate']:.4f} | {s['v3']['rate']:.4f} | "
                     f"{b['mean']:+.4f} | [{b['ci'][0]:+.4f}, {b['ci'][1]:+.4f}] | "
                     f"{mc['wins']}/{mc['losses']}/{mc['ties']} | {mc['p_two_sided_exact']:.3g} |")
    L += ["", "### 언어별", "", "| 색인 | 검색기 | 영어 v2→v3 | 한국어 v2→v3 |", "|---|---|---|---|"]
    for imode, block in o["results"].items():
        for name, r in block.items():
            e, k = r["by_subgroup"]["en"], r["by_subgroup"]["ko"]
            L.append(f"| {imode} | {name} | {e['v2']['rate']:.4f} → {e['v3']['rate']:.4f} | "
                     f"{k['v2']['rate']:.4f} → {k['v3']['rate']:.4f} |")
    if o["truncation"]:
        L += ["", "## 왜 dense 가 오르지 않는가 — 인코더 절단", "",
              "| 색인 | 코퍼스 | eCFR 중앙 토큰수 | max_seq 초과(잘림) |", "|---|---|---:|---:|"]
        for imode, pair in o["truncation"].items():
            for ver, p in pair.items():
                L.append(f"| {imode} | {ver} | {p['median_tokens']} | "
                         f"{p['truncated']}/{p['n']} ({p['truncated_share']*100:.0f}%) |")
        L += ["", f"> MiniLM 의 `max_seq_length` 는 128 토큰이다. v3 `full_text` 에서는 "
              "복구한 본문의 절반 이상이 인코더에 들어가지도 못한다. "
              "`minimal_text` 는 첫 문장 260자 상한이라 애초에 본문이 색인에 거의 안 들어간다.", ""]
    qa = o.get("query_anchor") or {}
    if qa.get("jaccard_query_vs_heading") is not None:
        L += ["## 더 근본적인 이유 — 질의가 표제에 정박해 있다", "",
              f"| 대상 | 질의와의 평균 Jaccard |", "|---|---:|",
              f"| 표제(heading) | **{qa['jaccard_query_vs_heading']:.4f}** |",
              f"| 복구한 Items 본문 | {qa['jaccard_query_vs_items']:.4f} |",
              "", f"(n={qa['n']})", "",
              "> 검증 질의는 **그 당시 코퍼스에 있던 텍스트, 즉 표제를 읽고 역생성**됐다. "
              "그래서 질의는 표제에 약 2배 더 가깝다. 나중에 본문을 채워 넣어도 질의가 "
              "그것을 보고 쓰인 적이 없으므로 매칭에 기여하지 못하고, dense 에서는 오히려 "
              "표현을 희석시킨다. **코퍼스만 고쳐서는 해결되지 않으며, 질의셋을 풍부해진 "
              "코퍼스에 맞춰 다시 만들면 자기참조가 되살아난다.**", ""]
    v = o["verdict"]
    L += ["## 판정", "", f"**{v['label']}**", "", v["text"], "",
          "## 그래서 무엇을 할 것인가", "",
          "- `combined_v3.json` 은 **채택하지 않고 아티팩트로 보존**한다. 채택 근거가 없다.",
          "- 이 음성 결과는 논문 한계 절에 쓸 수 있다: 표제 스텁이 상한 요인이라는 "
          "그럴듯한 가설을 세우고, 코퍼스를 실제로 고쳐 측정했고, 반증됐다.",
          "- 절대 성능(R@10 0.58)의 상한은 코퍼스 완전성이 아니라 다른 데 있다. "
          "질의셋이 역생성이라는 점, 라벨공간이 eCFR 한정이라는 점이 남은 후보다.",
          "- `audit_label_quality.is_stub` 는 문구 기준이라 본문 복구를 감지하지 못한다. "
          "v3를 쓰지 않더라도 이 정의 문제는 `docs/corpus_v3_stub_recovery.md` 에 기록해 둔다.",
          ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
